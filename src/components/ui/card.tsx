  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      // Uses the one canonical surface so Card, .surface and .glass are the
      // same shape everywhere. Card was rounded-2xl while every hand-rolled
      // card was rounded-xl — a mismatch you feel before you can name it.
      "surface text-card-foreground",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

